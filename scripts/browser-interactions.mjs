async (page) => {
  const baseURL = new URL(page.url()).origin;
  const checked = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); checked.push(message); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(`${baseURL}/`);
  await page.getByRole("button", { name: "Residential", exact: true }).click();
  check(await page.locator(".project-card").count() === 1, "Residential filter shows one matching project");
  const projectTrigger = page.getByRole("link", { name: "View A private address in Ikoyi" });
  await projectTrigger.click();
  await page.waitForURL("**/projects/ikoyi-residence/");
  check(await page.getByRole("heading", { name: "A private address in Ikoyi", exact: true, level: 1 }).count() === 1, "Project opens as a dedicated page with the selected content");
  check(await page.locator("dialog").count() === 0 && new URL(page.url()).pathname === "/projects/ikoyi-residence/", "Project has its own address and full page layout");
  await page.getByRole("link", { name: "Back to all projects", exact: true }).click();
  await page.waitForURL("**/#projects");
  check(await page.locator("#projects").isVisible(), "Back to all projects returns to the portfolio");
  await page.getByRole("button", { name: "Specialist", exact: true }).click();
  check(await page.locator(".project-card").count() === 1, "Specialist filter shows the laboratory");
  await page.getByRole("button", { name: "All projects", exact: true }).click();
  await page.getByRole("button", { name: "View all projects", exact: true }).click();
  check(await page.locator(".project-card").count() === 5, "View all projects reveals the full portfolio");
  await page.getByRole("button", { name: "Explore this service", exact: true }).first().click();
  check(await page.getByRole("button", { name: "Less detail", exact: true }).getAttribute("aria-expanded") === "true", "Service details expand accessibly");
  await page.getByRole("button", { name: "Less detail", exact: true }).click();
  check(await page.getByRole("button", { name: "Explore this service", exact: true }).count() === 3, "Service details collapse");
  await page.getByRole("button", { name: "Prepare enquiry", exact: true }).click();
  check(await page.getByRole("heading", { name: "Your enquiry is ready.", exact: true }).count() === 0, "Empty enquiry is rejected");
  await page.getByLabel("Your name", { exact: true }).fill("Demo Visitor");
  await page.getByLabel("Email address", { exact: true }).fill("visitor@example.com");
  await page.getByLabel("How can we help?", { exact: true }).selectOption("Quantity surveying");
  await page.getByLabel("Tell us about your project", { exact: true }).fill("We are planning a residential development in Lagos.");
  await page.getByRole("button", { name: "Prepare enquiry", exact: true }).click();
  await page.getByRole("heading", { name: "Your enquiry is ready.", exact: true }).waitFor();
  const draftHref = await page.getByRole("link", { name: "Open email draft", exact: true }).getAttribute("href");
  check(draftHref.startsWith("mailto:info@seasurveyorsltd.com?") && decodeURIComponent(draftHref).includes("visitor@example.com"), "Enquiry prepares an accurate email draft without sending");
  await page.getByLabel("Your name", { exact: true }).fill("Updated Visitor");
  check(await page.getByRole("link", { name: "Open email draft", exact: true }).count() === 0, "Editing form details invalidates the previous draft");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  check(await page.getByRole("button", { name: "Close navigation", exact: true }).getAttribute("aria-expanded") === "true", "Mobile navigation opens");
  await page.keyboard.press("Escape");
  check(await page.getByRole("button", { name: "Open navigation", exact: true }).getAttribute("aria-expanded") === "false", "Escape closes mobile navigation");
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  await page.getByRole("navigation", { name: "Mobile navigation", exact: true }).getByRole("link", { name: "Expertise", exact: true }).click();
  check(await page.getByRole("button", { name: "Open navigation", exact: true }).getAttribute("aria-expanded") === "false", "Choosing a section closes mobile navigation");
  check(await page.locator("header").evaluate((element) => Math.abs(element.getBoundingClientRect().top) < 1), "Navigation stays sticky after scrolling");
  check(await page.locator(".hero-photo").evaluate((element) => getComputedStyle(element).transform === "none"), "Reduced motion disables hero parallax");
  await page.goto(`${baseURL}/privacy/`);
  check(await page.getByRole("heading", { name: "Privacy, kept simple.", exact: true }).count() === 1, "Privacy route works");
  return { checked, total: checked.length };
}
